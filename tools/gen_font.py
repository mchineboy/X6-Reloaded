#!/usr/bin/env python3
"""Generate src/ui/font_data.c from assets/ui/x6-pixel.font.

  gen_font.py          rewrite the C table
  gen_font.py --check  fail if the committed table is stale
"""
import argparse
from pathlib import Path
import sys

ROWS = 9
FIRST, LAST = 32, 126


def parse(text):
    glyphs, current, name = {}, None, None
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.rstrip('\n')
        if line.startswith('#') and name is None:
            continue
        if len(line) == 3 and line[0] == '[' and line[2] == ']':
            if name is not None:
                glyphs[name] = current
            name, current = line[1], []
            if name in glyphs:
                raise ValueError(f'line {number}: duplicate glyph {name!r}')
            continue
        if not line.strip():
            continue
        if name is None:
            raise ValueError(f'line {number}: row before first glyph header')
        if set(line) - {'#', '.'}:
            raise ValueError(f'line {number}: glyph rows use only # and .')
        current.append(line)
    if name is not None:
        glyphs[name] = current
    table = []
    for code in range(FIRST, LAST + 1):
        char = chr(code)
        rows = glyphs.get(char)
        if rows is None:
            raise ValueError(f'missing glyph {char!r}')
        if len(rows) not in (7, ROWS):
            raise ValueError(f'glyph {char!r}: expected 7 or 9 rows, found {len(rows)}')
        width = len(rows[0])
        if not 1 <= width <= 8 or any(len(row) != width for row in rows):
            raise ValueError(f'glyph {char!r}: rows must share a width of 1-8')
        rows = rows + ['.' * width] * (ROWS - len(rows))
        bits = [sum(1 << x for x, c in enumerate(row) if c == '#') for row in rows]
        table.append((char, width, bits))
    extra = set(glyphs) - {chr(c) for c in range(FIRST, LAST + 1)}
    if extra:
        raise ValueError(f'unsupported glyphs: {sorted(extra)}')
    return table


def render(table):
    out = ['/* Generated by tools/gen_font.py from assets/ui/x6-pixel.font. Do not edit. */',
           '#include "x6_ui.h"', '',
           f'const uint8_t x6_font_width[{len(table)}] = {{']
    for i in range(0, len(table), 16):
        out.append('    ' + ', '.join(str(w) for _, w, _ in table[i:i + 16]) + ',')
    out += ['};', '', f'/* Bit x set = ink in column x (bit 0 is the left edge). */',
            f'const uint8_t x6_font_rows[{len(table)}][{ROWS}] = {{']
    for char, _, bits in table:
        label = {'\\': 'backslash', '*': 'asterisk', '/': 'slash'}.get(char, char)
        out.append('    {' + ', '.join(f'0x{b:02x}' for b in bits) + f'}}, /* {label} */')
    out += ['};', '']
    return '\n'.join(out)


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = root / 'assets/ui/x6-pixel.font'
    target = root / 'src/ui/font_data.c'
    try:
        generated = render(parse(source.read_text()))
    except ValueError as error:
        sys.exit(f'Font error: {error}')
    if args.check:
        if not target.is_file() or target.read_text() != generated:
            sys.exit('src/ui/font_data.c is stale; run tools/gen_font.py')
        print('Font table matches assets/ui/x6-pixel.font.')
        return
    target.write_text(generated)
    print(f'Wrote {target.relative_to(root)}')


if __name__ == '__main__':
    main()
